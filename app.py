for cat_idx, category in enumerate(checklist_data):
    with st.expander(f"📌 {category['category']}", expanded=True):
        for item in category["items"]:
            total_tasks += 1
            col1, col2 = st.columns([3, 2])

            with col1:
                is_checked = st.checkbox(
                    f"**{item['id']}** {item['task']}", key=item["id"]
                )
                if is_checked:
                    completed_tasks += 1

            with col2:
                if item["note"]:
                    st.info(f"💡 **注意事項：**\n\n{item['note']}")

progress_percentage = (
    (completed_tasks / total_tasks) if total_tasks > 0 else 0.0
)
st.sidebar.title("📊 當前作業進度")
st.sidebar.progress(progress_percentage)
st.sidebar.write(
    f"完成進度：**{completed_tasks} / {total_tasks}** ({int(progress_percentage * 100)}%)"
)

if completed_tasks == total_tasks:
    st.sidebar.success("🎉 太棒了！今日調配室作業 Check List 已全部完成！")
